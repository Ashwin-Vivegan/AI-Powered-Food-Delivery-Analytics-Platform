
-- 1. Food
COPY INTO FOOD_DELIVERY_DB.RAW.RAW_FOOD
    (SOURCE_INDEX, F_ID, ITEM, VEG_OR_NON_VEG)
FROM (
    SELECT $1, $2, $3, $4
    FROM @FOOD_DELIVERY_DB.RAW.FOOD_S3_STAGE/food.csv
)
FILE_FORMAT = (
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
)
ON_ERROR = 'ABORT_STATEMENT';

