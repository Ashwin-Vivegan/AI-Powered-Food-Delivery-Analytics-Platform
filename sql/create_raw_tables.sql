
CREATE TABLE IF NOT EXISTS FOOD_DELIVERY_DB.RAW.RAW_FOOD (
    SOURCE_INDEX VARCHAR,
    F_ID VARCHAR,
    ITEM VARCHAR,
    VEG_OR_NON_VEG VARCHAR
);

CREATE TABLE IF NOT EXISTS FOOD_DELIVERY_DB.RAW.RAW_MENU (
    SOURCE_INDEX VARCHAR,
    MENU_ID VARCHAR,
    R_ID VARCHAR,
    F_ID VARCHAR,
    CUISINE VARCHAR,
    PRICE VARCHAR
);

CREATE TABLE IF NOT EXISTS FOOD_DELIVERY_DB.RAW.RAW_ORDER_ITEMS (
    ORDER_ITEM_ID VARCHAR,
    ORDER_ID VARCHAR,
    R_ID VARCHAR,
    F_ID VARCHAR,
    PRICE VARCHAR,
    QUANTITY VARCHAR,
    LINE_AMOUNT VARCHAR
);

CREATE TABLE IF NOT EXISTS FOOD_DELIVERY_DB.RAW.RAW_RESTAURANT (
    SOURCE_INDEX VARCHAR,
    ID VARCHAR,
    NAME VARCHAR,
    CITY VARCHAR,
    RATING VARCHAR,
    RATING_COUNT VARCHAR,
    COST VARCHAR,
    CUISINE VARCHAR,
    LIC_NO VARCHAR,
    LINK VARCHAR,
    ADDRESS VARCHAR,
    MENU VARCHAR
);

CREATE TABLE IF NOT EXISTS FOOD_DELIVERY_DB.RAW.RAW_REVIEWS (
    REVIEW_ID VARCHAR,
    ORDER_ID VARCHAR,
    USER_ID VARCHAR,
    RESTAURANT_ID VARCHAR,
    RATING VARCHAR,
    COMMENT VARCHAR,
    REVIEW_DATE VARCHAR
);

-- Deliberately exclude name, email, password, and other direct identifiers
-- from the initial analytical ingestion of users.csv.
CREATE TABLE IF NOT EXISTS FOOD_DELIVERY_DB.RAW.RAW_USERS (
    USER_ID VARCHAR,
    AGE VARCHAR,
    GENDER VARCHAR,
    MARITAL_STATUS VARCHAR,
    OCCUPATION VARCHAR,
    MONTHLY_INCOME VARCHAR,
    EDUCATIONAL_QUALIFICATIONS VARCHAR,
    FAMILY_SIZE VARCHAR
);
